	public delegate void KeyEventHandler(object sender, KeyEventArgs e);

	// Only what SHDN scripts read: the modifier keys held right now (enRage checks Shift with it).
	public static class Control
	{
		[DllImport("user32.dll")]
		static extern short GetAsyncKeyState(int vKey);

		static bool Down(Keys k) => (GetAsyncKeyState((int)k) & 0x8000) != 0;

		public static Keys ModifierKeys =>
			(Down(Keys.ShiftKey) ? Keys.Shift : Keys.None) | (Down(Keys.ControlKey) ? Keys.Control : Keys.None) | (Down(Keys.Menu) ? Keys.Alt : Keys.None);
	}

	public class KeyEventArgs : EventArgs
	{
		public KeyEventArgs(Keys keyData) { KeyData = keyData; }
		public Keys KeyData { get; }
		public Keys KeyCode => KeyData & Keys.KeyCode;
		public int KeyValue => (int)(KeyData & Keys.KeyCode);
		public Keys Modifiers => KeyData & Keys.Modifiers;
		public bool Alt => (KeyData & Keys.Alt) == Keys.Alt;
		public bool Control => (KeyData & Keys.Control) == Keys.Control;
		public bool Shift => (KeyData & Keys.Shift) == Keys.Shift;
		public bool Handled { get; set; }
		public bool SuppressKeyPress { get; set; }
	}
