#!/usr/bin/env bash
# Regenerates api/Compat/*/Forwards.cs: every public top-level type of RDR2Coop.Api (for ScriptHookRDRNetAPI) and the
# WinForms shim's types in RDR2Coop.Core (for System.Windows.Forms). Run after changing the API's public types.
# --check (build.sh): fail if the committed files are stale instead of writing them.
set -euo pipefail
cd "$(dirname "$0")/.."
dotnet build api/Api/RDR2Coop.Api.csproj -c Release -nologo -v q > /dev/null
dotnet build api/Compat/gen/Gen.csproj -c Release -nologo -v q > /dev/null
out=api/Api/bin/Release/net9.0
gen() { echo "// Generated by tools/gen-compat-forwards.sh: don't edit."; dotnet api/Compat/gen/bin/Release/net9.0/Gen.dll "$@"; }
put() { if [ "${1:-}" = --check ]; then diff -q <(cat) "$2" > /dev/null || { echo "$2 is stale: run tools/gen-compat-forwards.sh" >&2; exit 1; }; else cat > "$2"; fi; }
gen "$out/RDR2Coop.Api.dll" "$out" | put "${1:-}" api/Compat/ScriptHookRDRNetAPI/Forwards.cs
gen "$out/RDR2Coop.Core.dll" "$out" System.Windows.Forms | put "${1:-}" api/Compat/System.Windows.Forms/Forwards.cs
[ "${1:-}" = --check ] && echo "api/Compat forwards up to date" || wc -l api/Compat/*/Forwards.cs
